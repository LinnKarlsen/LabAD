library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity RX_uart_TESTER is
    Port ( baud_rate_clk : in STD_LOGIC;
           serial : out STD_LOGIC);
end RX_uart_TESTER;

architecture Behavioral of RX_uart_TESTER is

    --constant testbench : STD_LOGIC_VECTOR (0 to 124) := "11111111111111111111011111111011111100001001001111110001101000111111111111111011110000011111111110010101100111111100111010001";
    --constant testbench : STD_LOGIC_VECTOR (0 to 222) := "1111111111111111111111111111111111101111111111111111101000010011111111111111111110110000101111111111111111111111111111111111111111111111101111000011111111111111111111110101001101111111111111111111111111111111011100001111111";
    constant testbench : STD_LOGIC_VECTOR (0 to 246) := "0111111111111111111111111110100001001111111111111111111111111111111111101100001011111111111111111100000111111111111111111111111111111111111111111111111101010011011111111111111111111111111111111111111111111111101110000111111111111111111111111111111";
    --constant testbench : STD_LOGIC_VECTOR (0 to 165) := "0111111111111111111111111110000000001111111111111111111111000000000111111111111111111000001111111111111111100001000111111111110000000001111111111111111111111111111111";
    
    signal counter : INTEGER := 0;
    constant counter_max : INTEGER := 246;

begin
    process(baud_rate_clk)
    begin
        if rising_edge(baud_rate_clk) then
            if counter < counter_max then
                counter <= counter + 1;
            else
                counter <= 0;
            end if;
            serial <= testbench(counter);
        end if;
    end process;
end Behavioral;
